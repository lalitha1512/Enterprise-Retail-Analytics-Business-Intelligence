-- 1. ROW COUNTS FOR ALL NINE TABLES

SELECT 'CUSTOMERS' TABLE_NAME, COUNT(*) TOTAL_RECORDS FROM CUSTOMERS
UNION ALL
SELECT 'ORDERS', COUNT(*) FROM ORDERS
UNION ALL
SELECT 'ORDER_ITEMS', COUNT(*) FROM ORDER_ITEMS
UNION ALL
SELECT 'PAYMENTS', COUNT(*) FROM PAYMENTS
UNION ALL
SELECT 'REVIEWS', COUNT(*) FROM REVIEWS
UNION ALL
SELECT 'PRODUCTS', COUNT(*) FROM PRODUCTS
UNION ALL
SELECT 'SELLERS', COUNT(*) FROM SELLERS
UNION ALL
SELECT 'GEOLOCATION', COUNT(*) FROM GEOLOCATION
UNION ALL
SELECT 'CATEGORY_TRANSLATION', COUNT(*) FROM CATEGORY_TRANSLATION;

-- 2. PRIMARY KEY VALIDATION

SELECT TABLE_NAME, CONSTRAINT_NAME, STATUS
FROM USER_CONSTRAINTS
WHERE CONSTRAINT_TYPE = 'P'
ORDER BY TABLE_NAME;

-- 3. FOREIGN KEY VALIDATION

SELECT TABLE_NAME, CONSTRAINT_NAME, STATUS
FROM USER_CONSTRAINTS
WHERE CONSTRAINT_TYPE = 'R'
ORDER BY TABLE_NAME;

-- 4. CHECK FOR INVALID DATABASE OBJECTS

SELECT OBJECT_NAME, OBJECT_TYPE, STATUS
FROM USER_OBJECTS
WHERE STATUS = 'INVALID';

-- 5. DUPLICATE CHECK: ORDER_ITEMS COMPOSITE KEY

SELECT ORDER_ID, ORDER_ITEM_ID, COUNT(*)
FROM ORDER_ITEMS
GROUP BY ORDER_ID, ORDER_ITEM_ID
HAVING COUNT(*) > 1;

-- 6. DUPLICATE CHECK: PAYMENTS COMPOSITE KEY

SELECT ORDER_ID, PAYMENT_SEQUENTIAL, COUNT(*)
FROM PAYMENTS
GROUP BY ORDER_ID, PAYMENT_SEQUENTIAL
HAVING COUNT(*) > 1;

-- 7. DUPLICATE CHECK: REVIEWS COMPOSITE KEY

SELECT REVIEW_ID, ORDER_ID, COUNT(*)
FROM REVIEWS
GROUP BY REVIEW_ID, ORDER_ID
HAVING COUNT(*) > 1;

-- 8. FOREIGN KEY ORPHAN CHECKS

-- Orders without matching customers
SELECT COUNT(*) ORPHAN_ORDERS
FROM ORDERS o
WHERE NOT EXISTS (
    SELECT 1 FROM CUSTOMERS c
    WHERE c.CUSTOMER_ID = o.CUSTOMER_ID
);

-- Order items without matching orders
SELECT COUNT(*) ORPHAN_ORDER_ITEMS
FROM ORDER_ITEMS oi
WHERE NOT EXISTS (
    SELECT 1 FROM ORDERS o
    WHERE o.ORDER_ID = oi.ORDER_ID
);

-- Order items without matching products
SELECT COUNT(*) ORPHAN_PRODUCTS
FROM ORDER_ITEMS oi
WHERE NOT EXISTS (
    SELECT 1 FROM PRODUCTS p
    WHERE p.PRODUCT_ID = oi.PRODUCT_ID
);

-- Order items without matching sellers
SELECT COUNT(*) ORPHAN_SELLERS
FROM ORDER_ITEMS oi
WHERE NOT EXISTS (
    SELECT 1 FROM SELLERS s
    WHERE s.SELLER_ID = oi.SELLER_ID
);

-- Payments without matching orders
SELECT COUNT(*) ORPHAN_PAYMENTS
FROM PAYMENTS p
WHERE NOT EXISTS (
    SELECT 1 FROM ORDERS o
    WHERE o.ORDER_ID = p.ORDER_ID
);

-- Reviews without matching orders
SELECT COUNT(*) ORPHAN_REVIEWS
FROM REVIEWS r
WHERE NOT EXISTS (
    SELECT 1 FROM ORDERS o
    WHERE o.ORDER_ID = r.ORDER_ID
);

