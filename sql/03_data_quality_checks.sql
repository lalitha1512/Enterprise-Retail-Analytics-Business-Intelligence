-- 1. CHECK INVALID PAYMENT INSTALLMENTS

SELECT ORDER_ID, PAYMENT_TYPE, PAYMENT_INSTALLMENTS, PAYMENT_VALUE
FROM PAYMENTS
WHERE PAYMENT_INSTALLMENTS < 1;

-- 2. CHECK NEGATIVE PAYMENT VALUES

SELECT COUNT(*) NEGATIVE_PAYMENT_VALUES
FROM PAYMENTS
WHERE PAYMENT_VALUE < 0;

-- 3. CHECK NEGATIVE PRODUCT PRICES

SELECT COUNT(*) NEGATIVE_PRODUCT_PRICES
FROM ORDER_ITEMS
WHERE PRICE < 0;

-- 4. CHECK NEGATIVE FREIGHT VALUES

SELECT COUNT(*) NEGATIVE_FREIGHT_VALUES
FROM ORDER_ITEMS
WHERE FREIGHT_VALUE < 0;

-- 5. CHECK NULL VALUES IN IMPORTANT COLUMNS

SELECT COUNT(*) NULL_CUSTOMER_IDS
FROM ORDERS
WHERE CUSTOMER_ID IS NULL;

SELECT COUNT(*) NULL_PRODUCT_IDS
FROM ORDER_ITEMS
WHERE PRODUCT_ID IS NULL;

SELECT COUNT(*) NULL_SELLER_IDS
FROM ORDER_ITEMS
WHERE SELLER_ID IS NULL;

SELECT COUNT(*) NULL_PAYMENT_VALUES
FROM PAYMENTS
WHERE PAYMENT_VALUE IS NULL;

SELECT COUNT(*) NULL_PRODUCT_PRICES
FROM ORDER_ITEMS
WHERE PRICE IS NULL;

-- 6. ORDER STATUS DISTRIBUTION

SELECT ORDER_STATUS, COUNT(*) TOTAL_ORDERS
FROM ORDERS
GROUP BY ORDER_STATUS
ORDER BY TOTAL_ORDERS DESC;

-- 7. PAYMENT TYPE DISTRIBUTION

SELECT PAYMENT_TYPE, COUNT(*) TOTAL_PAYMENTS
FROM PAYMENTS
GROUP BY PAYMENT_TYPE
ORDER BY TOTAL_PAYMENTS DESC;

-- 8. REVIEW SCORE DISTRIBUTION

SELECT REVIEW_SCORE, COUNT(*) TOTAL_REVIEWS
FROM REVIEWS
GROUP BY REVIEW_SCORE
ORDER BY REVIEW_SCORE DESC;

-- 9. FIND PRODUCT CATEGORIES WITHOUT ENGLISH TRANSLATION

SELECT DISTINCT p.PRODUCT_CATEGORY_NAME
FROM PRODUCTS p
LEFT JOIN CATEGORY_TRANSLATION ct
ON p.PRODUCT_CATEGORY_NAME = ct.PRODUCT_CATEGORY_NAME
WHERE ct.PRODUCT_CATEGORY_NAME IS NULL;

