-- 1. TOTAL PRODUCT REVENUE

SELECT ROUND(SUM(PRICE),2) TOTAL_REVENUE
FROM ORDER_ITEMS;

-- 2. TOTAL ORDERS

SELECT COUNT(DISTINCT ORDER_ID) TOTAL_ORDERS
FROM ORDERS;

-- 3. TOTAL UNIQUE CUSTOMERS

SELECT COUNT(DISTINCT CUSTOMER_UNIQUE_ID) TOTAL_CUSTOMERS
FROM CUSTOMERS;

-- 4. TOTAL PRODUCTS

SELECT COUNT(DISTINCT PRODUCT_ID) TOTAL_PRODUCTS
FROM PRODUCTS;

-- 5. TOTAL SELLERS

SELECT COUNT(DISTINCT SELLER_ID) TOTAL_SELLERS
FROM SELLERS;

-- 6. AVERAGE ORDER VALUE

SELECT ROUND(SUM(PRICE)/COUNT(DISTINCT ORDER_ID),2) AVERAGE_ORDER_VALUE
FROM ORDER_ITEMS;

-- 7. REVENUE BY ORDER STATUS

SELECT o.ORDER_STATUS, ROUND(SUM(oi.PRICE),2) REVENUE
FROM ORDERS o
JOIN ORDER_ITEMS oi ON o.ORDER_ID=oi.ORDER_ID
GROUP BY o.ORDER_STATUS
ORDER BY REVENUE DESC;

-- 8. MONTHLY REVENUE

SELECT TO_CHAR(o.ORDER_PURCHASE_TIMESTAMP,'YYYY-MM') MONTH,
ROUND(SUM(oi.PRICE),2) REVENUE
FROM ORDERS o
JOIN ORDER_ITEMS oi ON o.ORDER_ID=oi.ORDER_ID
GROUP BY TO_CHAR(o.ORDER_PURCHASE_TIMESTAMP,'YYYY-MM')
ORDER BY MONTH;

-- 9. TOP 10 PRODUCT CATEGORIES BY REVENUE

SELECT * FROM (
    SELECT p.PRODUCT_CATEGORY_NAME, ROUND(SUM(oi.PRICE),2) REVENUE
    FROM ORDER_ITEMS oi
    JOIN PRODUCTS p ON oi.PRODUCT_ID=p.PRODUCT_ID
    GROUP BY p.PRODUCT_CATEGORY_NAME
    ORDER BY REVENUE DESC
)
WHERE ROWNUM <= 10;

-- 10. TOP 10 SELLERS BY REVENUE

SELECT * FROM (
    SELECT s.SELLER_ID, ROUND(SUM(oi.PRICE),2) REVENUE
    FROM ORDER_ITEMS oi
    JOIN SELLERS s ON oi.SELLER_ID=s.SELLER_ID
    GROUP BY s.SELLER_ID
    ORDER BY REVENUE DESC
)
WHERE ROWNUM <= 10;

-- 11. TOTAL PAYMENT VALUE BY PAYMENT TYPE

SELECT PAYMENT_TYPE, ROUND(SUM(PAYMENT_VALUE),2) TOTAL_PAYMENT
FROM PAYMENTS
GROUP BY PAYMENT_TYPE
ORDER BY TOTAL_PAYMENT DESC;

-- 12. TOP 10 CUSTOMER STATES BY CUSTOMER COUNT

SELECT * FROM (
    SELECT CUSTOMER_STATE,
    COUNT(DISTINCT CUSTOMER_UNIQUE_ID) TOTAL_CUSTOMERS
    FROM CUSTOMERS
    GROUP BY CUSTOMER_STATE
    ORDER BY TOTAL_CUSTOMERS DESC
)
WHERE ROWNUM <= 10;

-- 13. ORDER STATUS DISTRIBUTION

SELECT ORDER_STATUS, COUNT(*) TOTAL_ORDERS,
ROUND(COUNT(*)*100/(SELECT COUNT(*) FROM ORDERS),2) PERCENTAGE
FROM ORDERS
GROUP BY ORDER_STATUS
ORDER BY TOTAL_ORDERS DESC;

-- 14. AVERAGE REVIEW SCORE

SELECT ROUND(AVG(REVIEW_SCORE),2) AVERAGE_REVIEW_SCORE
FROM REVIEWS;

-- 15. REVIEW SCORE DISTRIBUTION

SELECT REVIEW_SCORE, COUNT(*) TOTAL_REVIEWS,
ROUND(COUNT(*)*100/(SELECT COUNT(*) FROM REVIEWS),2) PERCENTAGE
FROM REVIEWS
GROUP BY REVIEW_SCORE
ORDER BY REVIEW_SCORE DESC;

-- 16. AVERAGE ACTUAL DELIVERY TIME IN DAYS

SELECT ROUND(AVG(
CAST(ORDER_DELIVERED_CUSTOMER_DATE AS DATE) -
CAST(ORDER_PURCHASE_TIMESTAMP AS DATE)
),2) AVG_DELIVERY_DAYS
FROM ORDERS
WHERE ORDER_DELIVERED_CUSTOMER_DATE IS NOT NULL;

-- 17. AVERAGE ESTIMATED DELIVERY WINDOW IN DAYS

SELECT ROUND(AVG(
CAST(ORDER_ESTIMATED_DELIVERY_DATE AS DATE) -
CAST(ORDER_PURCHASE_TIMESTAMP AS DATE)
),2) AVG_ESTIMATED_DAYS
FROM ORDERS
WHERE ORDER_ESTIMATED_DELIVERY_DATE IS NOT NULL;

-- 18. NUMBER OF LATE DELIVERIES

SELECT COUNT(*) LATE_DELIVERIES
FROM ORDERS
WHERE ORDER_DELIVERED_CUSTOMER_DATE >
ORDER_ESTIMATED_DELIVERY_DATE;

-- 19. LATE DELIVERY PERCENTAGE

SELECT ROUND(
SUM(CASE
    WHEN ORDER_DELIVERED_CUSTOMER_DATE >
         ORDER_ESTIMATED_DELIVERY_DATE
    THEN 1 ELSE 0
END)*100/COUNT(*),2) LATE_DELIVERY_PERCENTAGE
FROM ORDERS
WHERE ORDER_DELIVERED_CUSTOMER_DATE IS NOT NULL
AND ORDER_ESTIMATED_DELIVERY_DATE IS NOT NULL;

-- 20. AVERAGE FREIGHT COST PER ORDER ITEM

SELECT ROUND(AVG(FREIGHT_VALUE),2) AVG_FREIGHT_COST
FROM ORDER_ITEMS;

-- 21. TOP 10 CUSTOMER STATES BY PRODUCT REVENUE

SELECT * FROM (
    SELECT c.CUSTOMER_STATE, ROUND(SUM(oi.PRICE),2) REVENUE
    FROM CUSTOMERS c
    JOIN ORDERS o ON c.CUSTOMER_ID=o.CUSTOMER_ID
    JOIN ORDER_ITEMS oi ON o.ORDER_ID=oi.ORDER_ID
    GROUP BY c.CUSTOMER_STATE
    ORDER BY REVENUE DESC
)
WHERE ROWNUM <= 10;

-- 22. AVERAGE PAYMENT VALUE BY PAYMENT TYPE

SELECT PAYMENT_TYPE, ROUND(AVG(PAYMENT_VALUE),2) AVG_PAYMENT_VALUE
FROM PAYMENTS
GROUP BY PAYMENT_TYPE
ORDER BY AVG_PAYMENT_VALUE DESC;

-- 23. REPEAT CUSTOMERS

SELECT COUNT(*) REPEAT_CUSTOMERS
FROM (
    SELECT c.CUSTOMER_UNIQUE_ID
    FROM CUSTOMERS c
    JOIN ORDERS o ON c.CUSTOMER_ID=o.CUSTOMER_ID
    GROUP BY c.CUSTOMER_UNIQUE_ID
    HAVING COUNT(*) > 1
);

-- 24. REPEAT CUSTOMER PERCENTAGE

SELECT ROUND(r.REPEAT_CUSTOMERS*100/t.TOTAL_CUSTOMERS,2)
REPEAT_CUSTOMER_PERCENTAGE
FROM
(
    SELECT COUNT(*) REPEAT_CUSTOMERS
    FROM (
        SELECT c.CUSTOMER_UNIQUE_ID
        FROM CUSTOMERS c
        JOIN ORDERS o ON c.CUSTOMER_ID=o.CUSTOMER_ID
        GROUP BY c.CUSTOMER_UNIQUE_ID
        HAVING COUNT(*) > 1
    )
) r,
(
    SELECT COUNT(DISTINCT CUSTOMER_UNIQUE_ID) TOTAL_CUSTOMERS
    FROM CUSTOMERS
) t;

